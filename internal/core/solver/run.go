package solver

import (
	"math/rand"
	"time"
)

// Воспроизводимость запуска (ADR-0023).
//
// Улучшение останавливается по времени, а за одно и то же время на разных машинах (и даже
// на одной, при разной нагрузке) поиск успевает сделать разное число раундов. Поэтому один
// лишь сид запуск не воспроизводит. Запуск записывает сид и сколько раундов улучшения он
// сделал; повтор берёт тот же сид и останавливается ровно на том же раунде — результат
// совпадает пара в пару, сколько бы времени ни заняло.
//
// Раунд — одна итерация внешнего цикла метода: толчок + сходимость в ILS, разрушение +
// восстановление в LNS, шаг табу-поиска, поколение генетического алгоритма. Раунд, который
// оборвало время, отбрасывается и не считается: иначе повтор (без ограничения по времени)
// довёл бы его до конца и получил бы другое расписание.
//
// Имитация отжига так не воспроизводится: её температура зависит от прошедшего времени.

// runBudget — когда остановить улучшение и сколько раундов сделано.
type runBudget struct {
	deadline  time.Time
	maxRounds int // > 0 — повтор: ровно столько раундов, время не важно
	rounds    int // сколько раундов сделано до конца
}

// replaying — это повтор записанного запуска (остановка по раундам).
func (b *runBudget) replaying() bool { return b.maxRounds > 0 }

// nextRound — можно ли начать ещё один раунд.
func (b *runBudget) nextRound() bool {
	if b.replaying() {
		return b.rounds < b.maxRounds
	}
	return !time.Now().After(b.deadline)
}

// startRound — начать раунд, который время оборвать не может (внутри нет сходимости до
// срока, как в шаге табу-поиска): раунд засчитывается сразу.
func (b *runBudget) startRound() bool {
	if !b.nextRound() {
		return false
	}
	b.rounds++
	return true
}

// roundDone засчитывает раунд. false — время вышло посреди раунда (только при обычном
// запуске): раунд надо отбросить, вернув расписание к лучшему, и закончить.
func (b *runBudget) roundDone() bool {
	if !b.replaying() && time.Now().After(b.deadline) {
		return false
	}
	b.rounds++
	return true
}

// innerDeadline — срок для сходимости внутри раунда. При повторе сходимость не
// обрывается: в записанном запуске засчитаны только раунды, дошедшие до конца.
func (b *runBudget) innerDeadline() time.Time {
	if b.replaying() {
		return time.Now().Add(24 * time.Hour)
	}
	return b.deadline
}

// newRNG — генератор случайных чисел с сидом seed.
func newRNG(seed int64) *rand.Rand { return rand.New(rand.NewSource(seed)) }
